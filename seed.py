SCHEMA = """
PRAGMA foreign_keys = ON;

CREATE TABLE product (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    name            TEXT    NOT NULL,
    description     TEXT,
    price           NUMERIC(10, 2) NOT NULL DEFAULT 0,
    category        TEXT,
    unit            TEXT,
    active_substance TEXT,
    is_active       INTEGER NOT NULL DEFAULT 1,
    deadline        TEXT,          -- рок на употреба
    stock           INTEGER,
    default_dosage  TEXT            -- општа доза (fallback); специфичната живее во recommendation
);

CREATE TABLE crop (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    name        TEXT    NOT NULL UNIQUE,
    description TEXT,
    is_active   INTEGER NOT NULL DEFAULT 1,
    created_at  TEXT    NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE disease (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    name        TEXT    NOT NULL UNIQUE,
    description TEXT,
    is_active   INTEGER NOT NULL DEFAULT 1,
    created_at  TEXT    NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE growth_phase (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    name        TEXT    NOT NULL UNIQUE,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    period_from TEXT,              -- ориентирен почеток на фазата
    period_to   TEXT,              -- ориентировен крај на фазата
    is_active   INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE recommendation (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    crop_id     INTEGER NOT NULL,
    disease_id  INTEGER NOT NULL,
    -- phase_id е ОПЦИОНАЛНА: NULL значи „важи за СИТЕ фази“ (пр. пламеница на лозје)
    phase_id    INTEGER,
    product_id  INTEGER NOT NULL,
    dosage      TEXT    NOT NULL,
    notes       TEXT,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    is_active   INTEGER NOT NULL DEFAULT 1,
    created_at  TEXT    NOT NULL DEFAULT (datetime('now')),
    FOREIGN KEY (crop_id)    REFERENCES crop(id)        ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (disease_id) REFERENCES disease(id)     ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (phase_id)   REFERENCES growth_phase(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (product_id) REFERENCES product(id)     ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Уникатност: една препорака по култура+болест+производ за конкретна фаза...
CREATE UNIQUE INDEX idx_rec_unique_phase
    ON recommendation (crop_id, disease_id, phase_id, product_id)
    WHERE phase_id IS NOT NULL;
-- ...и само една препорака „за сите фази“ по култура+болест+производ.
CREATE UNIQUE INDEX idx_rec_unique_allphases
    ON recommendation (crop_id, disease_id, product_id)
    WHERE phase_id IS NULL;

CREATE INDEX idx_rec_disease ON recommendation (disease_id);
CREATE INDEX idx_rec_phase   ON recommendation (phase_id);
CREATE INDEX idx_rec_product ON recommendation (product_id);
"""

